VALID = {"safe", "irrelevant", "violation", "gray"}


def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    rows = []
    for x in data:
        lab = LABELS.get(x["id"])
        if lab not in VALID:
            raise SystemExit(f"第 {x['id']} 条未标注或标签非法: {lab}")
        rows.append({"id": x["id"], "text": x["text"], "label": lab})

    with open(dst, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    from collections import Counter
    c = Counter(r["label"] for r in rows)
    print(f"已标注 {len(rows)} 条 → {dst}")
    for k in ("safe", "irrelevant", "violation", "gray"):
        print(f"  {k:<11} {c[k]:>3} 条  {c[k]*100//len(rows):>3}%")
    print(f"  过滤率(irrelevant+violation) {(c['irrelevant']+c['violation'])*100/len(rows):.1f}%")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
